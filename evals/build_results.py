#!/usr/bin/env python3
"""Turns evals/receipts/results.json and evals/gym/results.json into evals/results.md."""
import json
from pathlib import Path

E = Path(__file__).resolve().parent
rc = json.loads((E / "receipts" / "results.json").read_text())
gy = json.loads((E / "gym" / "results.json").read_text())
n_lines = len((E / "gym" / "note.txt").read_text().splitlines())
pct = lambda x: "n/a" if x is None else f"{x * 100:.1f}%"

L = ["# Eval results", "", "Generated by `evals/run.sh`. Rerun it to reproduce the receipt numbers exactly; the gym numbers come from a model, so they can move a little.", ""]
L += ["## 1. Receipt parser (local, no model, `import_receipts`)", "",
      f"{rc['cases']} made-up Lidl US receipts, {rc['truth_items']} food items in the hand-written truth files (`evals/receipts/cases/*.truth.json`).", "",
      "| Metric | Result |", "| --- | --- |",
      f"| Item recall (truth items found by name) | {pct(rc['item_recall'])} |",
      f"| Item precision (parsed items that are real) | {pct(rc['item_precision'])} |",
      f"| Price match, after line discounts (found items) | {pct(rc['price_match'])} |",
      f"| Quantity and unit match (found items) | {pct(rc['qty_unit_match'])} |",
      f"| Date match | {pct(rc['date_match'])} |",
      f"| Card or merchant data left in the payload | {rc['card_data_leaks']} |",
      f"| Unrecognised layout sent to the Claude fallback | {rc['unrecognised_routed_to_claude']} |", ""]
bad = [c for c in rc["per_case"] if c["missed"] or c["wrong"] or c["extra"] or c["leaks"]]
L += ["What the eval found and what changed:", "",
      "- Count and weight lines written without a `$` (`4 @ 0.99`, `1.6 lb @ 4.00/lb`) were ignored, so a 1.6 lb item counted as 1 item (qty/unit match 87.5% on the first run). Fixed by making the `$` optional in both copies of the regex (`mcp/penthouse_mcp/receipts.py`, `scripts/lidl_sync.py`).",
      "- A payment block that starts with `VISA ****9999` instead of `Card` was not cut, so the card digits, auth code and approval number stayed in the text. Fixed by adding card brands and `Auth`, `Approval`, `Tender` to the cut list in both copies. The leak count above is measured on the cut text and the payload of every case.",
      f"- Still open: an item name wrapped over two lines (`ORGANIC BABY SPINACH` then `ENTREE 3.29 F`) is read as the item `ENTREE`, so recall is {pct(rc['item_recall'])}. Not fixed, because I haven't seen a real Lidl receipt wrap names.", ""]
if bad:
    L += ["Cases with misses right now: " + ", ".join(f"`{c['case']}`" for c in bad), ""]
L += ["Limits: the cases are made up by me in the layouts the app handles, so these numbers say the parser does what I designed it to do, not how it does on every real receipt. The Claude paths (receipt photos, `estimateItems`, size guessing) are not evaluated here yet: they need receipt screenshots and API spend.", ""]
L += ["## 2. Gym note parser (`gym-data-parser` agent, headless Claude Code)", "",
      f"Input: my real Apple Notes gym note (`evals/gym/note.txt`, {n_lines} lines, messy on purpose: typos, `x` skipped weeks, lines with several weights, remarks). {gy['checks']} checks, each a fact I worked out by counting lines by hand (`CHECKS` in `evals/gym/score.py`). {gy['runs']} runs ({gy.get('failed_runs', 0)} failed to produce an answer).", "",
      "The scorer itself is checked with a negative control: `python3 evals/gym/score.py --selftest` shows that an empty answer passes none of the checks.",
      f"Checks passed per run: {gy['per_run_passed']} of {gy['checks']}.", "",
      "| Check | Passes |", "| --- | --- |"]
for cid, n in gy["per_check_passes"].items():
    L.append(f"| `{cid}` | {n}/{gy['runs']} |")
L += ["", "Notes:", "",
      "- My first version of four checks matched exercise names too literally (the parser writes `Pull-up`, `Cable lateral raise`, and reads the note's `include DB press (5)` as an incline press). The parser was right, and I loosened the name matching after looking at its output. So these checks are not fully blind.",
      "- The truth is about one note. It is a regression test for that note, not a measure of how the parser does on any note.", ""]
(E / "results.md").write_text("\n".join(L))
print("wrote evals/results.md")
